const L1_SET = new Set(L1_INDUSTRIES)
const RULE_INDEX = RULES.map(([kw, group]) => ({ kw, group }))

/**
 * 关键字会让少数板块串门，这里做显式覆盖（先于规则表命中）：
 *  - 「炼化及贸易」含「贸易」，会被商贸零售先截走，实为石油石化二级
 *  - 「非金属材料Ⅱ/Ⅲ」含「非金属材料」，会被建筑材料先截走，实为基础化工二级
 * 每条都必须给出理由，避免覆盖表变成黑盒。
 */
const EXACT_GROUP = {
  炼化及贸易: '石油石化',
  非金属材料: '基础化工',
}

/** 去掉 Ⅱ / Ⅲ 后缀，得到可匹配的名称主干 */
export function baseName(name) {
  return String(name || '').replace(/[ⅡⅢ]+$/g, '').trim()
}

/**
 * 确定性归组：先精确命中一级行业，再按有序关键字表匹配。
 * @returns {{group: string, rule: string|null, exact: boolean}}
 */
export function classify(name) {
  const base = baseName(name)
  if (L1_SET.has(base)) return { group: base, rule: 'exact', exact: true }
  if (EXACT_GROUP[base]) return { group: EXACT_GROUP[base], rule: 'override', exact: true }
  for (const { kw, group } of RULE_INDEX) {
    if (base.includes(kw)) return { group, rule: kw, exact: false }
  }
  return { group: '未归类', rule: null, exact: false }
}

export { RULES, EXACT_GROUP }
